package com.example.smartflow.node.slot;

/**
 * 收集节点缺信息时怎么追问。两种方式里，"已记录了什么、哪里填错了、这轮问哪几项"都由代码决定，
 * 区别只在追问那一句话由谁来说。
 */
public enum AskMode {
    /**
     * 已记录信息和校验提示由代码立刻输出；追问由模型按代码给出的追问计划措辞并流式输出，
     * 能回应"我再想想""你推荐一个"这类话。模型超时、出错或没有输出时退回 {@link #CODE} 的文案。
     */
    MODEL,
    /** 全部由代码生成，不调用模型 */
    CODE
}
